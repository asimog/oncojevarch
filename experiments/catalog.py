def _a(
    number: int,
    question: str,
    hypothesis: str,
    data: tuple[str, ...],
    capabilities: tuple[str, ...],
    comparison: tuple[str, ...],
    metrics: tuple[str, ...],
    failure: tuple[str, ...],
    consequences: tuple[str, ...],
    *,
    level: EvaluationLevel = EvaluationLevel.SYNTHETIC,
    executable: bool = False,
    success: tuple[str, ...] | None = None,
) -> ExperimentSpec:
    return ExperimentSpec(
        experiment_id=f"A{number:03d}",
        experiment_class=ExperimentClass.ARCHITECTURE,
        question=question,
        hypothesis=hypothesis,
        required_data=data,
        required_capabilities=capabilities,
        comparison=comparison,
        metrics=metrics,
        success_criteria=success
        or ("prespecified comparison is completed", "all metrics are recorded"),
        failure_criteria=failure,
        decision_consequences=consequences,
        budget={"max_wall_minutes": 30, "max_live_repetitions": 3},
        evaluation_level=level,
        executable=executable,
    )


